  const storeRow = async (payload: Record<string, unknown>): Promise<boolean> => {
    const total = supabaseClients.length;
    if (total === 0) return false;

    let accepted = -1;

    for (let step = 0; step < total; step++) {
      const idx = (activeNodeRef.current + step) % total;
      try {
        const { error } = await supabaseClients[idx].from("copilot_sessions").insert(payload);
        if (!error) { accepted = idx; break; }
        console.warn("node rejected insert:", error.message);
      } catch (err) {
        console.warn("node threw on insert:", err);
      }
    }

    if (accepted === -1) return false;

    activeNodeRef.current = accepted;

    if (MIRROR_WIDTH > 0) {
      const targets = Array.from({ length: total }, (_, i) => (accepted + 1 + i) % total)
        .filter((idx) => idx !== accepted);

      void (async () => {
        let next = 0;
        const worker = async () => {
          while (next < targets.length) {
            const idx = targets[next++];
            try {
              await supabaseClients[idx].from("copilot_sessions").insert(payload);
            } catch { /* one copy is already stored */ }
          }
        };
        await Promise.all(
          Array.from({ length: Math.min(MIRROR_WIDTH, targets.length) }, worker),
        );
      })();
    }

    return true;
  };

  const writeControl = async (code: string, state: "open" | "closed") => {
    await Promise.all(supabaseClients.map(async (client) => {
      try {
        await client.from("copilot_control").upsert(
          {
            session_code: code,
            state,
            closed_at: state === "closed" ? new Date().toISOString() : null,
            updated_at: new Date().toISOString(),
          },
          { onConflict: "session_code" },
        );
      } catch (err) {
        console.warn("control write failed:", err);
      }
    }));
  };

  // ── bulk frame sweep ───────────────────────────────────────
  const sweepFrames = async (onPage?: (seen: number) => void): Promise<FrameRow[]> => {
    const collected: FrameRow[] = [];

    for (const client of supabaseClients) {
      for (let from = 0; ; from += SWEEP_PAGE) {
        const { data, error } = await client
          .from("copilot_sessions")
          .select("id,batch_id,image_url")
          .eq("kind", "frame")
          .not("image_url", "is", null)
          .order("created_at", { ascending: true })
          .order("id", { ascending: true })
          .range(from, from + SWEEP_PAGE - 1);

        if (error) {
          console.warn("sweep page failed:", error.message);
          break;
        }
        if (!data || data.length === 0) break;

        collected.push(...(data as FrameRow[]));
        onPage?.(collected.length);
        if (data.length < SWEEP_PAGE) break;
      }
    }

    const seen = new Set<string>();
    return collected.filter((r) => !seen.has(r.id) && (seen.add(r.id), true));
  };

